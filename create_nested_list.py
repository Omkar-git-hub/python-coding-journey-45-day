"""
Create a Nested List

This script demonstrates how to create a nested list (a list of lists) in Python.
It defines a nested list containing three sublists, each with three integers,
and prints the resulting nested list to the console.
"""

def main():
    # Define a nested list: a list containing three sublists
    nested_list = [
        [1, 2, 3],
        [4, 5, 6],
        [7, 8, 9]
    ]

    # Print the nested list
    print("Nested List:")
    print(nested_list)

if __name__ == "__main__":
    main()