"""
use_for_loop.py

This script demonstrates the use of a `for` loop in Python.
It iterates over a list of items and prints each one.
"""

def main() -> None:
    """
    Iterate over a list of items and print each item.
    """
    items = ["apple", "banana", "cherry"]
    for item in items:
        print(item)

if __name__ == "__main__":
    main()