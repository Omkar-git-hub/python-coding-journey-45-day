def function_with_parameters(a: int, b: int, c: int) -> int:
    """
    Return the sum of three integer parameters.

    Parameters
    ----------
    a : int
        First integer.
    b : int
        Second integer.
    c : int
        Third integer.

    Returns
    -------
    int
        The sum of a, b, and c.
    """
    return a + b + c