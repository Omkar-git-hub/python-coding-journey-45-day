def create_list_using_range(start: int, end: int, step: int = 1) -> list[int]:
    """
    Create a list of integers using Python's built-in range function.

    Args:
        start (int): The starting integer of the range (inclusive).
        end (int): The ending integer of the range (exclusive).
        step (int, optional): The step/increment between numbers. Defaults to 1.

    Returns:
        list[int]: A list containing the sequence of integers generated by range.
    """
    # Validate inputs to ensure step is not zero to avoid ValueError
    if step == 0:
        raise ValueError("step argument must not be zero")
    return list(range(start, end, step))


